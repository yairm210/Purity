/**
 * Unifies, for each function-level annotation, the four things every one of them needs:
 *  A. [fqName] - the annotation's FqName
 *  B. the user-configured well-known function names for it (from [PurityConfig])
 *  C. [isExplicitlyMarked] - is a function marked as this annotation, directly, via well-known FQN
 *     (built-in or user config), or because it overrides a function that is
 *  D. [validate] - given a function marked/expected to be this annotation, check that its body
 *     actually follows the annotation's rules, reporting + returning any violations
 *
 * Note: [isExplicitlyMarked] only covers the mechanical annotation/FQN/override matching that is common
 * to all three. @Pure and @Readonly have additional structural heuristics layered on top of this
 * (autogenerated functions, single-statement returns, well-known *classes*, etc.) in
 * [ExpectedFunctionPurityChecker] - isExplicitlyMarked is the shared core those build on, not the full story.
 */
enum class FunctionAnnotations(
    val fqName: FqName,
    private val wellKnownFunctions: Set<String>,
    private val wellKnownFunctionsFromUser: (PurityConfig) -> Set<String>,
) {
    Pure(
        Annotations.Pure,
        wellKnownPureFunctions,
        { it.wellKnownPureFunctionsFromUser },
    ) {
        override fun validate(function: IrFunction, purityConfig: PurityConfig, messageCollector: MessageCollector): List<String> {
            val visitor = CheckFunctionPurityVisitor(function, FunctionPurity.Pure, messageCollector, purityConfig)
            function.accept(visitor, Unit)
            return visitor.reportedMessages
        }
    },

    Readonly(
        Annotations.Readonly,
        wellKnownReadonlyFunctions,
        { it.wellKnownReadonlyFunctionsFromUser },
    ) {
        override fun validate(function: IrFunction, purityConfig: PurityConfig, messageCollector: MessageCollector): List<String> {
            val visitor = CheckFunctionPurityVisitor(function, FunctionPurity.Readonly, messageCollector, purityConfig)
            function.accept(visitor, Unit)
            return visitor.reportedMessages
        }
    },

    ReturnsNewInstance(
        Annotations.ReturnsNewInstance,
        wellKnownNewInstanceFunctions,
        { it.wellKnownNewInstanceFunctionsFromUser },
    ) {
        override fun validate(function: IrFunction, purityConfig: PurityConfig, messageCollector: MessageCollector): List<String> =
            validateReturnsNewInstance(function, purityConfig, messageCollector)
    };

    /** Is [function] marked as this annotation - directly, via well-known FQN (built-in or user config),
     * or because it overrides a function that is. */
    fun isExplicitlyMarked(function: IrFunction, purityConfig: PurityConfig): Boolean {
        if (function.hasAnnotation(fqName)) return true

        val fqn = function.fqNameForIrSerialization.asString()
        if (fqn in wellKnownFunctions) return true
        if (fqn in wellKnownFunctionsFromUser(purityConfig)) return true

        if (function is IrSimpleFunction) {
            for (overriddenFunction in getAllOverriddenFunctions(function)) {
                if (overriddenFunction.hasAnnotation(fqName)) return true
                val overriddenFqn = overriddenFunction.fqNameForIrSerialization.asString()
                if (overriddenFqn in wellKnownFunctions) return true
                if (overriddenFqn in wellKnownFunctionsFromUser(purityConfig)) return true
            }
        }
        return false
    }

    /** Checks that [function], expected to follow this annotation's rules, actually does -
     * reports any violations via [messageCollector] (respecting @TestExpectCompileError) and
     * returns the reported messages (empty if valid). */
    abstract fun validate(function: IrFunction, purityConfig: PurityConfig, messageCollector: MessageCollector): List<String>
}

/** A @ReturnsNewInstance function (or override of one) must only return: a constructor call, a call to
 * another @ReturnsNewInstance function, or a local val that was itself assigned from one of those. */
private fun validateReturnsNewInstance(
    function: IrFunction,
    purityConfig: PurityConfig,
    messageCollector: MessageCollector,
): List<String> {
    if (!FunctionAnnotations.ReturnsNewInstance.isExplicitlyMarked(function, purityConfig)) return emptyList()

    val errorSeverity = if (function.hasAnnotation(Annotations.TestExpectCompileError)) CompilerMessageSeverity.WARNING else CompilerMessageSeverity.ERROR
    val newInstanceVariables = HashSet<IrVariable>()
    val messages = mutableListOf<String>()

    val visitor = object : IrVisitor<Unit, Unit>() {
        override fun visitVariable(declaration: IrVariable, data: Unit) {
            // Unwrap safe calls (a?.b()) so e.g. `val x = a?.returnsNewInstanceFun()` is seen through
            val initializer = declaration.initializer?.let { unwrapSafeCall(it) }
            if (!declaration.isVar) {
                if (initializer is IrConstructorCall) newInstanceVariables.add(declaration)
                if (initializer is IrCall && FunctionAnnotations.ReturnsNewInstance.isExplicitlyMarked(initializer.symbol.owner, purityConfig)) {
                    newInstanceVariables.add(declaration)
                }
            }
            super.visitVariable(declaration, data)
        }

        override fun visitReturn(expression: IrReturn, data: Unit) {
            if (expression.returnTargetSymbol == function.symbol) {
                val value = unwrapSafeCall(expression.value)
                val isNewInstance = when (value) {
                    is IrConstructorCall -> true
                    is IrCall -> FunctionAnnotations.ReturnsNewInstance.isExplicitlyMarked(value.symbol.owner, purityConfig)
                    is IrGetValue -> value.symbol.owner.let { it is IrVariable && it in newInstanceVariables }
                    else -> false
                }
                if (!isNewInstance) {
                    val message = "Function \"${function.name}\" is marked as (or overrides a function marked as) @ReturnsNewInstance " +
                        "but returns a value that is not a constructor call, a call to another @ReturnsNewInstance function, " +
                        "or a local val assigned from one of those.\n"
                    messageCollector.report(errorSeverity, message, getLocationForExpression(function, expression))
                    messages.add(message)
                }
            }
            super.visitReturn(expression, data)
        }

        override fun visitElement(element: IrElement, data: Unit) {
            element.acceptChildren(this, data)
        }
    }
    function.accept(visitor, Unit)
    return messages
}
